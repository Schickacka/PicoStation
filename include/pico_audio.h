#pragma once

#include <stddef.h>
#include <stdint.h>

#include "ff.h"
#include "subq.h"

namespace picostation {

// Wire format for SD:/PicoPlayer/ metadata transferred to PS1 via sector 5000..5009
// Must match PpWireTrack in picomenu/src/picoplayer/picoplayer.c!
static constexpr uint16_t kPicoAudioMaxTracks = 99;
static constexpr uint16_t kPicoAudioTracksPerSector = 16;

enum PicoAudioFmt : uint8_t {
    PICO_AUDIO_FMT_CDDA = 0,
    PICO_AUDIO_FMT_MP3  = 1,
    PICO_AUDIO_FMT_WAV  = 2,
};

struct __attribute__((packed)) PicoAudioWireTrack {
    char     title[36];
    char     artist[32];
    char     album[32];
    uint8_t  format;        // PicoAudioFmt
    uint8_t  trackNum;      // 1..99
    uint16_t bitrateKbps;
    uint16_t sampleRateHz;
    uint32_t lengthSectors; // 75 sectors/sec
};
static_assert(sizeof(PicoAudioWireTrack) == 110, "PicoAudioWireTrack size mismatch");

class PicoAudio {
  public:
    PicoAudio() = default;
    ~PicoAudio() = default;

    // Scans SD:/PicoPlayer/ for .mp3 and .wav files and builds a virtual Red Book TOC.
    uint16_t scanFolder();

    // Provides idle pioSamples[2..31] (~141 KB) as a zero-heap arena while PicoPlayer is active.
    void setScratchArena(void *base, size_t capacity);

    // Activates virtual Audio CD mode (uses scratch arena — 0 bytes heap, CACHED_SECS=32 untouched!).
    bool activate();

    // Deactivates virtual Audio CD mode, closes open file, frees all heap buffers.
    void deactivate();

    bool isActive() const { return m_active; }
    uint16_t getTrackCount() const { return m_trackCount; }
    uint32_t getTotalSectors() const { return m_totalSectors; }

    // Builds one metadata sector (page 0..6) into m_metaBuf (100% RAM, zero SD I/O!).
    void prepareMetaPage(uint32_t page);
    uint16_t *getMetaBuffer(uint32_t page);

    // Opens & reads 16,896-byte .cov album art (8 parts x 2114 B, "PART"/"DEAD").
    void openArt(uint16_t trackIdx);
    uint16_t *readArtPart(uint32_t part);

    // Virtual Red Book Audio CD SubQ + I2S sector synthesis.
    SubQ::Data generateSubQ(const int sector);
    void readSector(uint32_t *i2sBuffer, const int sector);

  private:
    struct __attribute__((packed)) TrackEntry {
        char     filename[128];
        char     title[36];
        char     artist[28];
        char     album[28];
        uint8_t  format;
        uint8_t  channels;
        uint8_t  hasArt;
        uint8_t  pad;
        uint16_t bitrateKbps;
        uint16_t sampleRateHz;
        uint32_t dataOffset;
        uint32_t dataBytes;
        uint32_t startSector;
        uint32_t lengthSectors;
    };
    static_assert(sizeof(TrackEntry) == 244, "TrackEntry packed size mismatch");

    // Precomputed TOC cache header generated by PicoManager (SD:/PicoPlayer/index.pp)
    struct __attribute__((packed)) IndexHeader {
        char     magic[4];      // "PPT1"
        uint16_t version;       // 1
        uint16_t trackCount;    // 1..99
        uint16_t dirFileCount;  // total .mp3 + .wav + .cov files in /PicoPlayer/
        uint16_t reserved;      // 0
        uint32_t dirHashXor;    // order-independent XOR of per-file FNV-1a(lower(name)+0xFF+le32(size))
        uint32_t dirHashSum;    // order-independent SUM of per-file FNV-1a(...)
    };
    static_assert(sizeof(IndexHeader) == 20, "IndexHeader size mismatch");

    // Lives inside idle pioSamples[2..31] (~141 KB arena — 0 bytes heap/BSS!)
    struct PlaybackBuffers {
        static constexpr size_t kInBufSize  = 16384; // 16 KB (~400 ms @ 320 kbps, zero SD reads during decode!)
        static constexpr size_t kPcmRingCap = 6144;  // 3072 stereo frames (fits 4x upsampled MPEG-2.5)
        static constexpr size_t kClmtSize   = 64;    // FatFS fast-seek cluster link map
        DWORD    clmt[kClmtSize];
        uint8_t  mp3InBuf[kInBufSize];
        int16_t  pcmRing[kPcmRingCap];
        int16_t  frameOut[2304]; // MAX_NGRAN(2) * MAX_NCHAN(2) * MAX_NSAMP(576)
        int16_t  sectorPcm[1176];
    };

    // All PicoAudio tables & FatFS structs live inside idle pioSamples[2..31]
    // (~141 KB) while in PicoMenu / PicoPlayer, so g_picoAudio consumes ~48 B
    // of static .bss (leaving 40+ KB free RP2040 heap for 57..99-track PS1 games!).
    struct ArenaState {
        TrackEntry      tracks[kPicoAudioMaxTracks];
        FIL             fp;
        FIL             artFp;
        uint16_t        metaBuf[1162];
        PlaybackBuffers pb;
        DIR             scanDir;
        FILINFO         scanFno;
        TrackEntry      sortKey;
        uint8_t         tagScratch[128];
    };

    bool ensureArena(bool zeroAll);
    bool tryLoadIndex();
    bool probeWav(const char *path, TrackEntry &entry);
    bool probeMp3(const char *path, TrackEntry &entry);
    void readId3TagsFromOpenFile(uint32_t fileSize, char *title, size_t tSz, char *artist, size_t aSz, char *album, size_t alSz);
    bool openTrackFile(uint16_t trackIdx, uint32_t relSector);
    void closeTrackFile();
    void decodeMp3Sector(uint32_t *i2sBuffer, const TrackEntry &tr, uint32_t relSector);
    void decodeWavSector(uint32_t *i2sBuffer, const TrackEntry &tr, uint32_t relSector);

    ArenaState     *m_arena = nullptr;
    uint16_t        m_trackCount = 0;
    uint32_t        m_totalSectors = 0;
    volatile bool   m_active = false;
    bool            m_hasMp3 = false;

    // Active playback state (Core 1 only)
    bool            m_fpOpen = false;
    bool            m_artOpen = false;
    int             m_openTrackIdx = -1;
    uint32_t        m_expectedRelSector = 0;

    void           *m_mp3Dec = nullptr;
    int             m_mp3BytesLeft = 0;
    uint8_t        *m_mp3ReadPtr = nullptr;
    size_t          m_pcmCount = 0;
    uint32_t        m_resampPhase = 0; // Q16 fixed-point phase for non-44.1 kHz resampling
    int16_t         m_resampPrevL = 0;
    int16_t         m_resampPrevR = 0;
};

extern PicoAudio g_picoAudio;

}  // namespace picostation
